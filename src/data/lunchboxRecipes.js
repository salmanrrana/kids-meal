// Builds a self-contained SVG image (emoji on a soft gradient) so cards never
// show broken external images.
function foodImage(emoji, from, to) {
  const svg = `<svg xmlns="http://www.w3.org/2000/svg" width="800" height="600" viewBox="0 0 800 600"><defs><linearGradient id="g" x1="0" y1="0" x2="1" y2="1"><stop offset="0%" stop-color="${from}"/><stop offset="100%" stop-color="${to}"/></linearGradient></defs><rect width="800" height="600" rx="48" fill="url(#g)"/><circle cx="400" cy="290" r="190" fill="#ffffff" opacity="0.35"/><text x="400" y="360" font-size="220" text-anchor="middle">${emoji}</text></svg>`;
  return `data:image/svg+xml,${encodeURIComponent(svg)}`;
}

